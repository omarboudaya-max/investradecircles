-- This script creates the tables and seeds ALL existing sample data for:
-- - Governorates (24 regions of Tunisia)
-- - Economic Sectors (7 sectors)
-- - Investment Opportunities / Projects (8 initial opportunities)
-- - Investment Organizations / Investors (8 initial institutions & funds)
-- - Investment Vehicles / Funds (4 initial managed funds)
-- - Investor Interest expressions & Document requests
-- - Saved Investments
-- - Project Analytics Views
-- ==============================================================================

-- 1. Governorate Table
CREATE TABLE IF NOT EXISTS public."Governorate" (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  name_fr TEXT,
  region TEXT,
  code TEXT,
  created_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Sector Table
CREATE TABLE IF NOT EXISTS public."Sector" (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  icon TEXT,
  color TEXT,
  created_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. InvestmentOrganization Table (Investors & Institutions)
CREATE TABLE IF NOT EXISTS public."InvestmentOrganization" (
  id TEXT PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  display_name TEXT NOT NULL,
  legal_name TEXT,
  organization_type TEXT NOT NULL,
  country TEXT DEFAULT 'Tunisia',
  country_code TEXT DEFAULT 'TN',
  city TEXT,
  address TEXT,
  website TEXT,
  year_founded INTEGER,
  logo TEXT,
  logo_alt_text TEXT,
  verification_status TEXT DEFAULT 'VERIFIED',
  verification_source TEXT,
  official BOOLEAN DEFAULT false,
  featured BOOLEAN DEFAULT false,
  partner BOOLEAN DEFAULT false,
  is_illustrative BOOLEAN DEFAULT false,
  description TEXT,
  investment_focus TEXT[] DEFAULT '{}',
  geographic_focus TEXT[] DEFAULT '{}',
  investment_stages TEXT[] DEFAULT '{}',
  project_types TEXT[] DEFAULT '{}',
  minimum_ticket NUMERIC DEFAULT 0.1,
  maximum_ticket NUMERIC DEFAULT 5.0,
  preferred_currencies TEXT[] DEFAULT '{"TND"}',
  contact_email TEXT,
  contact_phone TEXT,
  logo_url TEXT,
  user_id TEXT,
  active BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. InvestmentVehicle Table (Funds & Vehicles)
CREATE TABLE IF NOT EXISTS public."InvestmentVehicle" (
  id TEXT PRIMARY KEY,
  organization_id TEXT REFERENCES public."InvestmentOrganization"(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  vehicle_type TEXT,
  fund_category TEXT,
  fund_status TEXT DEFAULT 'ACTIVE_INVESTING',
  country TEXT,
  currency TEXT DEFAULT 'TND',
  target_size NUMERIC,
  current_size NUMERIC,
  minimum_ticket NUMERIC,
  maximum_ticket NUMERIC,
  investment_stages TEXT[] DEFAULT '{}',
  sector_focus TEXT[] DEFAULT '{}',
  geographic_focus TEXT[] DEFAULT '{}',
  description TEXT,
  active BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. InvestmentProject Table (Opportunities)
CREATE TABLE IF NOT EXISTS public."InvestmentProject" (
  id TEXT PRIMARY KEY,
  project_code TEXT,
  title TEXT NOT NULL,
  company_name TEXT NOT NULL,
  promoter_name TEXT,
  city TEXT,
  governorate_id TEXT REFERENCES public."Governorate"(id) ON DELETE SET NULL,
  sector_id TEXT REFERENCES public."Sector"(id) ON DELETE SET NULL,
  investment_required NUMERIC DEFAULT 0,
  equity_required NUMERIC DEFAULT 0,
  debt_required NUMERIC DEFAULT 0,
  minimum_ticket NUMERIC DEFAULT 0,
  maximum_ticket NUMERIC DEFAULT 0,
  expected_roi NUMERIC DEFAULT 0,
  project_duration INTEGER DEFAULT 12,
  jobs_created INTEGER DEFAULT 0,
  investment_stage TEXT DEFAULT 'EXPANSION',
  project_type TEXT DEFAULT 'INDUSTRIAL',
  seeking TEXT[] DEFAULT '{}',
  target_markets TEXT[] DEFAULT '{}',
  export_potential TEXT DEFAULT 'MEDIUM',
  infrastructure_available BOOLEAN DEFAULT true,
  land_available BOOLEAN DEFAULT true,
  strategic_value TEXT,
  short_description TEXT,
  description TEXT,
  image_url TEXT,
  user_id TEXT,
  is_verified BOOLEAN DEFAULT true,
  featured BOOLEAN DEFAULT false,
  project_status TEXT DEFAULT 'PUBLISHED',
  email TEXT,
  phone TEXT,
  website TEXT,
  created_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Safe migrations in case tables already exist:
ALTER TABLE public."InvestmentOrganization" ADD COLUMN IF NOT EXISTS logo_url TEXT;
ALTER TABLE public."InvestmentOrganization" ADD COLUMN IF NOT EXISTS user_id TEXT;
ALTER TABLE public."InvestmentProject" ADD COLUMN IF NOT EXISTS image_url TEXT;
ALTER TABLE public."InvestmentProject" ADD COLUMN IF NOT EXISTS user_id TEXT;

-- 6. InvestorInterest Table
CREATE TABLE IF NOT EXISTS public."InvestorInterest" (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
  project_id TEXT REFERENCES public."InvestmentProject"(id) ON DELETE CASCADE,
  project_title TEXT,
  investor_user_id TEXT,
  investor_name TEXT NOT NULL,
  investor_email TEXT,
  investor_phone TEXT,
  investor_type TEXT,
  interest_type TEXT,
  proposed_amount NUMERIC,
  investment_capacity NUMERIC,
  preferred_ticket NUMERIC,
  message TEXT,
  mode TEXT DEFAULT 'interest',
  status TEXT DEFAULT 'NEW',
  created_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. SavedInvestment Table
CREATE TABLE IF NOT EXISTS public."SavedInvestment" (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
  user_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
  project_id TEXT REFERENCES public."InvestmentProject"(id) ON DELETE CASCADE,
  project_title TEXT,
  governorate_name TEXT,
  sector_name TEXT,
  investment_required NUMERIC,
  created_date TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. ProjectView Table
CREATE TABLE IF NOT EXISTS public."ProjectView" (
  id TEXT PRIMARY KEY DEFAULT gen_random_uuid()::text,
  project_id TEXT REFERENCES public."InvestmentProject"(id) ON DELETE CASCADE,
  governorate_id TEXT,
  sector_id TEXT,
  user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  action TEXT DEFAULT 'VIEW',
  timestamp TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Disable Row Level Security initially to match the main project configuration
ALTER TABLE public."Governorate" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."Sector" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."InvestmentOrganization" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."InvestmentVehicle" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."InvestmentProject" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."InvestorInterest" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."SavedInvestment" DISABLE ROW LEVEL SECURITY;
ALTER TABLE public."ProjectView" DISABLE ROW LEVEL SECURITY;

